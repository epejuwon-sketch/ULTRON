def generate_forge_project(
    db: Session,
    *,
    principal: Principal,
    settings: Settings,
    name: str,
    template: str,
    prompt: str,
    custom_files: dict[str, str] | None = None,
) -> dict[str, Any]:
    """Generate a complete multi-file project, run isolated validation + AEGIS scan, and archive to ZIP."""
    clean_tpl = template.strip().lower()
    if clean_tpl not in VALID_TEMPLATES:
        raise ValidationError(f"Unsupported template '{clean_tpl}'. Supported: {', '.join(sorted(VALID_TEMPLATES))}")

    files_map, preview_html = _build_template_files(name, clean_tpl, prompt)
    if custom_files:
        for k, v in custom_files.items():
            files_map[k.lstrip("/")] = v

    build_logs = [
        f"[{datetime.now(timezone.utc).isoformat()}] FORGE scaffolded {len(files_map)} files using template '{clean_tpl}'.",
        f"[{datetime.now(timezone.utc).isoformat()}] Running AEGIS static security & syntax verification...",
    ]
    aegis_verdict = scan_code_bundle(files_map)
    build_logs.append(
        f"[{datetime.now(timezone.utc).isoformat()}] AEGIS verdict: {'PASSED' if aegis_verdict['passed'] else 'FAILED'} "
        f"(findings={aegis_verdict['findings_count']})."
    )

    test_results = {
        "files_generated": len(files_map),
        "syntax_checks": aegis_verdict["syntax_checks"],
        "aegis_passed": aegis_verdict["passed"],
        "preview_ready": aegis_verdict["passed"],
    }

    archive_meta = create_zip_bundle_file(
        db,
        principal=principal,
        settings=settings,
        archive_name=f"forge_{name.lower().replace(' ', '_')}",
        files_map=files_map,
    )
    build_logs.append(f"[{datetime.now(timezone.utc).isoformat()}] Packaged ZIP archive: {archive_meta['file_id']}.")

    rec = ForgeProjectRecord(
        forge_id=f"frg_{uuid.uuid4().hex[:14]}",
        tenant_id=principal.tenant_id,
        name=name.strip()[:160],
        template=clean_tpl,
        prompt=prompt.strip(),
        status="VERIFIED" if aegis_verdict["passed"] else "FAILED",
        files_json=json.dumps(files_map),
        preview_html=preview_html if aegis_verdict["passed"] else "",
        build_logs_json=json.dumps(build_logs),
        test_results_json=json.dumps(test_results),
        aegis_verdict_json=json.dumps(aegis_verdict),
        archive_file_id=archive_meta["file_id"],
        created_by=principal.username,
    )
    db.add(rec)
    append_audit_log(
        db,
        tenant_id=principal.tenant_id,
        actor=principal.username,
        action="FORGE_PROJECT_GENERATED",
        resource=rec.forge_id,
        outcome=f"template={clean_tpl};status={rec.status};files={len(files_map)}",
    )
    db.commit()
    db.refresh(rec)
    return _serialize_forge(rec, include_files=True)


def list_forge_projects(db: Session, *, tenant_id: str, limit: int = 50) -> list[dict[str, Any]]:
    rows = db.execute(
        select(ForgeProjectRecord)
        .where(ForgeProjectRecord.tenant_id == tenant_id)
        .order_by(ForgeProjectRecord.created_at.desc())
        .limit(limit)
    ).scalars().all()
    return [_serialize_forge(r, include_files=False) for r in rows]


def get_forge_project(db: Session, *, tenant_id: str, forge_id: str) -> dict[str, Any]:
    rec = db.execute(
        select(ForgeProjectRecord).where(
            ForgeProjectRecord.forge_id == forge_id,
            ForgeProjectRecord.tenant_id == tenant_id,
        )
    ).scalar_one_or_none()
    if rec is None:
        raise NotFoundError(f"FORGE project '{forge_id}' not found.")
    return _serialize_forge(rec, include_files=True)


def update_forge_project(
    db: Session,
    *,
    principal: Principal,
    settings: Settings,
    forge_id: str,
    files: dict[str, str],
) -> dict[str, Any]:
    """Save edited FORGE workspace files, re-run AEGIS static verification, and rebuild ZIP archive."""
    rec = db.execute(
        select(ForgeProjectRecord).where(
            ForgeProjectRecord.forge_id == forge_id,
            ForgeProjectRecord.tenant_id == principal.tenant_id,
        )
    ).scalar_one_or_none()
    if rec is None:
        raise NotFoundError(f"FORGE project '{forge_id}' not found.")
    if not files:
        raise ValidationError("At least one file must be provided when updating a FORGE workspace.")

    files_map = {k.lstrip("/"): v for k, v in files.items() if k.strip()}
    aegis_verdict = scan_code_bundle(files_map)
    existing_logs = json.loads(rec.build_logs_json or "[]")
    ts = datetime.now(timezone.utc).isoformat()
    existing_logs.append(
        f"[{ts}] Saved {len(files_map)} file(s) by {principal.username}. AEGIS verdict: "
        f"{'PASSED' if aegis_verdict['passed'] else 'FAILED'} (findings={aegis_verdict['findings_count']})."
    )
    test_results = {
        "files_generated": len(files_map),
        "syntax_checks": aegis_verdict["syntax_checks"],
        "aegis_passed": aegis_verdict["passed"],
        "preview_ready": aegis_verdict["passed"],
    }
    archive_meta = create_zip_bundle_file(
        db,
        principal=principal,
        settings=settings,
        archive_name=f"forge_{rec.name.lower().replace(' ', '_')}",
        files_map=files_map,
    )
    if "index.html" in files_map and aegis_verdict["passed"]:
        rec.preview_html = files_map["index.html"]
    elif not aegis_verdict["passed"]:
        rec.preview_html = ""

    rec.files_json = json.dumps(files_map)
    rec.status = "VERIFIED" if aegis_verdict["passed"] else "FAILED"
    rec.build_logs_json = json.dumps(existing_logs[-50:])
    rec.test_results_json = json.dumps(test_results)
    rec.aegis_verdict_json = json.dumps(aegis_verdict)
    rec.archive_file_id = archive_meta["file_id"]
    rec.updated_at = datetime.now(timezone.utc)

    append_audit_log(
        db,
        tenant_id=principal.tenant_id,
        actor=principal.username,
        action="FORGE_PROJECT_UPDATED",
        resource=rec.forge_id,
        outcome=f"status={rec.status};files={len(files_map)}",
    )
    db.commit()
    db.refresh(rec)
    return _serialize_forge(rec, include_files=True)


def _serialize_forge(f: ForgeProjectRecord, *, include_files: bool = False) -> dict[str, Any]:
    files_map = json.loads(f.files_json or "{}")
    data: dict[str, Any] = {
        "forge_id": f.forge_id,
        "name": f.name,
        "template": f.template,
        "prompt": f.prompt,
        "status": f.status,
        "file_list": sorted(files_map.keys()),
        "build_logs": json.loads(f.build_logs_json or "[]"),
        "test_results": json.loads(f.test_results_json or "{}"),
        "aegis_verdict": json.loads(f.aegis_verdict_json or "{}"),
        "archive_file_id": f.archive_file_id,
        "archive_download_url": f"/api/v1/files/{f.archive_file_id}/download" if f.archive_file_id else None,
        "preview_available": bool(f.preview_html),
        "created_by": f.created_by,
        "created_at": f.created_at.isoformat(),
    }
    if include_files:
        data["files"] = files_map
        data["preview_html"] = f.preview_html
    return data
