def validate_registry_integrity() -> dict[str, Any]:
    """Validate that all 112 pages exist, have valid owners and valid agent references."""
    errors: list[str] = []
    seen_numbers = set()
    seen_page_ids = set()

    if len(PAGE_INTEGRATION_MATRIX) != 112:
        errors.append(f"Expected exactly 112 pages, found {len(PAGE_INTEGRATION_MATRIX)}")

    for p in PAGE_INTEGRATION_MATRIX:
        num = p["number"]
        pid = p["page_id"]

        if num in seen_numbers:
            errors.append(f"Duplicate page number {num}")
        seen_numbers.add(num)

        if pid in seen_page_ids:
            errors.append(f"Duplicate page_id {pid}")
        seen_page_ids.add(pid)

        # Primary agent check
        if p["primary_agent"] is not None and p["primary_agent"] not in VALID_AGENT_IDS:
            errors.append(f"Page {pid} references unknown primary_agent '{p['primary_agent']}'")

        # Supporting agents check
        for sup in p["supporting_agents"]:
            if sup not in VALID_AGENT_IDS:
                errors.append(f"Page {pid} references unknown supporting_agent '{sup}'")

        # Owner check (must have either primary agent or backend service)
        if not p["primary_agent"] and not p["backend_service"]:
            errors.append(f"Page {pid} has neither primary_agent nor backend_service owner")

    return {
        "valid": len(errors) == 0,
        "total_pages": len(PAGE_INTEGRATION_MATRIX),
        "errors": errors,
    }


def get_page_spec(page_num_or_id: int | str) -> PageIntegrationSpec | None:
    """Retrieve integration spec for a page by number (1..112) or string ID ('001'..'112')."""
    if isinstance(page_num_or_id, int):
        for p in PAGE_INTEGRATION_MATRIX:
            if p["number"] == page_num_or_id:
                return p
    else:
        pid = str(page_num_or_id).zfill(3)
        for p in PAGE_INTEGRATION_MATRIX:
            if p["page_id"] == pid:
                return p
    return None


def get_pages_for_agent(agent_id: str) -> dict[str, list[dict[str, Any]]]:
    """Find all pages where the given agent is primary or supporting."""
    primary_pages = []
    supporting_pages = []

    for p in PAGE_INTEGRATION_MATRIX:
        summary = {
            "page_id": p["page_id"],
            "number": p["number"],
            "name": p["name"],
            "subsystem": p["subsystem"],
            "module_id": p["module_id"],
            "subpage_id": p["subpage_id"],
            "status": p["integration_status"],
        }
        if p["primary_agent"] == agent_id:
            primary_pages.append(summary)
        elif agent_id in p["supporting_agents"]:
            supporting_pages.append(summary)

    return {
        "agent_id": agent_id,
        "primary_pages": primary_pages,
        "supporting_pages": supporting_pages,
        "total_owned": len(primary_pages),
        "total_supporting": len(supporting_pages),
    }
